from decimal import Decimal as D

import pytest

from app.services.currency import rs


@pytest.mark.parametrize("v,text", [
    (D("0"), "₹0.00"), (D("1"), "₹1.00"), (D("100"), "₹100.00"), (D("999"), "₹999.00"),
    (D("1000"), "₹1,000.00"), (D("5000"), "₹5,000.00"), (D("10000"), "₹10,000.00"), (D("100000"), "₹1,00,000.00"),
    (D("130940.50"), "₹1,30,940.50"), (D("97069.62"), "₹97,069.62"), (D("4447.80"), "₹4,447.80"),
    (D("15000000"), "₹1,50,00,000.00"), (D("1234567890.12"), "₹1,23,45,67,890.12"),
    (D("-4447.80"), "-₹4,447.80"), (D("-100000"), "-₹1,00,000.00"),
    (D("0.005"), "₹0.01"), (D("0.004"), "₹0.00"), (D("-0.004"), "₹0.00"), (D("999.995"), "₹1,000.00"),
    (D("99999.994"), "₹99,999.99"), (D("1.5"), "₹1.50"), (D("130940.5"), "₹1,30,940.50"),
    (5000, "₹5,000.00"), ("130940.50", "₹1,30,940.50"), (None, "-"),
])
def test_indian_grouping(v, text):
    assert rs(v) == text
